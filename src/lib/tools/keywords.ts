/**
 * Returns the curated SEO keywords for a specific tool slug,
 * falling back to generated sensible defaults if none are defined.
 */
export function getKeywordsForTool(slug: string, name?: string): string[] {
  const curated = TOOL_KEYWORDS[slug];
  if (curated && curated.length > 0) {
    return curated;
  }
  const toolName = name || slug.replace(/-/g, " ");
  return [
    toolName,
    `${toolName} free`,
    `${toolName} online`,
    `${toolName} no upload`,
    `cara pakai ${toolName}`,
    "free online file tool",
    "client-side converter",
    "private file processor",
  ];
}
